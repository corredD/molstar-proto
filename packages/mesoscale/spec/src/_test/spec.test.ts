import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { IssueCodes } from '../format/issues.js';
import { MesoQLSymbols } from '../format/mesoql.js';
import { DefaultResolvers } from '../resolvers/index.js';
import {
  anchorsOf,
  check,
  type CheckOptions,
  formatMarkdown,
  generateReference,
  load,
  MESOSCALE,
  SPEC_DIR,
  referenceFiles,
  SPEC_PACKAGE,
  slugOf,
} from '../../scripts/spec.js';

// The spec check (_spec/README.md, "Keeping the spec"): the references are the code's tables regenerated, the sources
// have Mol*'s header, the links between spec files resolve, and the issue codes sources report are registered. Each
// failure is proven on a copy in a temp folder, never on the repository's files.

let reference: Record<string, string>;
let tmp: string;
let n = 0;

beforeAll(async () => {
  reference = await generateReference();
  tmp = mkdtempSync(join(tmpdir(), 'meso-spec-'));
});
afterAll(() => rmSync(tmp, { recursive: true, force: true }));

const HEADER = `/**
 * Copyright (c) 2026 mol* contributors, licensed under MIT, See LICENSE file for more info.
 *
 * @author Ludovic Autin <autin@scripps.edu>
 */
`;

/** A copy of the spec folder and a source folder holding one clean file, to break one thing in. */
function sandbox(): CheckOptions & { src: string } {
  const root = join(tmp, `case-${n++}`);
  const spec = join(root, '_spec');
  const src = join(root, 'src');
  cpSync(SPEC_DIR, spec, { recursive: true });
  mkdirSync(src, { recursive: true });
  writeFileSync(join(src, 'a.ts'), `${HEADER}\nexport const a = 1;\n`);
  return { spec, sources: src, src, reference, issueCodes: IssueCodes, root };
}

describe('the repository', () => {
  it('passes the check', () => {
    expect(
      check({
        spec: SPEC_DIR,
        sources: MESOSCALE,
        codeSources: join(SPEC_PACKAGE, 'src'),
        reference,
        issueCodes: IssueCodes,
        root: MESOSCALE,
      }),
    ).toEqual([]);
  });

  it('references every issue code, symbol and resolver', () => {
    for (const code of Object.keys(IssueCodes)) expect(reference['issues.md']).toContain(`\`${code}\``);
    for (const s of MesoQLSymbols) expect(reference['mesoql.md']).toContain(`\`${s.name}\``);
    for (const r of DefaultResolvers) expect(reference['resolvers.md']).toContain(`\`${r.id}\``);
    expect(reference['format.md']).toContain('## MesoViewSpecDoc');
    expect(reference['format.md']).toContain('| `populations` |');
  });

  it('marks every reference as generated', () => {
    for (const text of Object.values(reference)) expect(text).toMatch(/^<!-- Generated by .* Do not edit/);
  });
});

describe('the check', () => {
  it('passes a clean sandbox', () => {
    expect(check(sandbox())).toEqual([]);
  });

  it('fails a stale reference table', () => {
    const o = sandbox();
    const f = join(o.spec, 'reference', 'issues.md');
    writeFileSync(f, readFileSync(f, 'utf8').replace('`id.duplicate`', '`id.duplicated`'));
    expect(check(o)).toEqual([expect.stringMatching(/reference\/issues\.md\tstale/)]);
  });

  it('fails after a MesoQL symbol or an issue code is added to the code and not regenerated', async () => {
    // the reference the generator would write for a code with one more symbol and one more issue code, against the
    // files written for the code as it is
    const l = await load();
    const grown = {
      ...l,
      issueCodes: { ...l.issueCodes, 'thing.new': 'A code added without regenerating' },
      symbols: [...l.symbols, { ...l.symbols[0], name: '(newsym)', full: 'newsym', example: '(newsym)' }],
    };
    const o = { ...sandbox(), reference: await formatMarkdown(referenceFiles(grown)) };
    expect(check(o).sort()).toEqual([
      expect.stringMatching(/reference\/issues\.md\tstale/),
      expect.stringMatching(/reference\/mesoql\.md\tstale/),
    ]);
  });

  it('fails a missing reference', () => {
    const o = sandbox();
    rmSync(join(o.spec, 'reference', 'resolvers.md'));
    const misses = check(o);
    expect(misses[0]).toMatch(/reference\/resolvers\.md\tmissing/);
    // the README's links to it break as well
    expect(misses.slice(1).every((m) => /README\.md:\d+\treference\/resolvers\.md: no such file/.test(m))).toBe(true);
  });

  it('fails a source without Mol*’s header, or with one that has no author', () => {
    const o = sandbox();
    writeFileSync(join(o.src, 'b.ts'), 'export const b = 1;\n');
    writeFileSync(
      join(o.src, 'c.tsx'),
      HEADER.replace(' * @author Ludovic Autin <autin@scripps.edu>\n', '') + 'export const c = 1;\n',
    );
    writeFileSync(join(o.src, 'd.d.ts'), 'export declare const d: number;\n');
    const misses = check(o);
    expect(misses).toHaveLength(2);
    expect(misses[0]).toMatch(/b\.ts:1\tno Mol\* header/);
    expect(misses[1]).toMatch(/c\.tsx:1\tthe header has no @author/);
  });

  it('fails a link to a missing file and a link to a missing heading', () => {
    const o = sandbox();
    const f = join(o.spec, 'views.md');
    writeFileSync(
      f,
      `${readFileSync(f, 'utf8')}\n[a](gone.md) [b](format.md#no-such-heading) [c](#nor-this) [d](format.md#shape) [e](https://example.org/x#y)\n\`[x](ignored.md)\`\n`,
    );
    expect(check(o)).toEqual([
      expect.stringMatching(/views\.md:\d+\tgone\.md: no such file/),
      expect.stringMatching(/views\.md:\d+\tformat\.md#no-such-heading: no such heading/),
      expect.stringMatching(/views\.md:\d+\t#nor-this: no such heading/),
    ]);
  });

  it('fails an issue code a source reports and the registry lacks', () => {
    const o = sandbox();
    writeFileSync(
      join(o.src, 'e.ts'),
      `${HEADER}\nissues.push(\n  issue(\n    'thing.broken',\n    'error',\n    'load',\n    'x',\n  ),\n);\nissue('id.duplicate', 'error', 'static', 'x');\n`,
    );
    expect(check(o)).toEqual([expect.stringMatching(/e\.ts:8\t"thing\.broken" is in no registry/)]);
  });

  it('fails a code a validate-style helper reports and the registry lacks', () => {
    const o = sandbox();
    mkdirSync(join(o.src, 'format'));
    writeFileSync(
      join(o.src, 'format', 'validate.ts'),
      `${HEADER}\nerr('id.duplicate', 'x');\nwarn(\n  'thing.warned',\n  'x',\n);\nerr('value.nonesuch', 'x');\n`,
    );
    expect(check(o)).toEqual([
      expect.stringMatching(/validate\.ts:8\t"thing\.warned" is in no registry/),
      expect.stringMatching(/validate\.ts:12\t"value\.nonesuch" is in no registry/),
    ]);
  });

  it('accepts a header with a year range or another year', () => {
    const o = sandbox();
    writeFileSync(join(o.src, 'f.ts'), HEADER.replace('2026', '2018-2026') + 'export const f = 1;\n');
    writeFileSync(join(o.src, 'g.ts'), HEADER.replace('2026', '2027') + 'export const g = 1;\n');
    expect(check(o)).toEqual([]);
  });

  it('fails links whose text wraps, that carry a title, or are reference-style', () => {
    const o = sandbox();
    const f = join(o.spec, 'views.md');
    writeFileSync(
      f,
      `${readFileSync(f, 'utf8')}\n[wrapped\ntext](gone1.md) [titled](gone2.md "a title")\n\n[ref]: gone3.md\n`,
    );
    expect(check(o)).toEqual([
      expect.stringMatching(/views\.md:\d+\tgone1\.md: no such file/),
      expect.stringMatching(/views\.md:\d+\tgone2\.md: no such file/),
      expect.stringMatching(/views\.md:\d+\tgone3\.md: no such file/),
    ]);
  });

  it('fails a MesoQL parser code the registry lacks', () => {
    const o = sandbox();
    mkdirSync(join(o.src, 'format'));
    writeFileSync(join(o.src, 'format', 'mesoql.ts'), `${HEADER}\nerr('syntax', 'x');\nerr('nonesuch', 'x');\n`);
    expect(check(o)).toEqual([expect.stringMatching(/mesoql\.ts:8\t"mesoql\.nonesuch" is in no registry/)]);
  });
});

describe('slugs', () => {
  it('are GitHub’s: punctuation and markup dropped, repeats numbered', () => {
    expect(slugOf('The `Foo` API (v2): what, why?')).toBe('the-foo-api-v2-what-why');
    const a = anchorsOf('# A\n\n## Same\n\n```\n## not a heading\n```\n\n## Same\n');
    expect([...a]).toEqual(['a', 'same', 'same-1']);
  });
});
