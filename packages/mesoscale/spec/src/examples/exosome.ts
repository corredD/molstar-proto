import type { MesoViewSpecDoc, Population } from '../format/doc.js';
import { importCellpackGpuRecipe, parseCellpackGpuRecipe } from '../resolvers/cellpack-gpu.js';
import recipeJson from './fixtures/exosome.cellpack-gpu.json' with { type: 'json' };
import { syntheticPicksStar, syntheticVesicleObj } from './fixtures/synthetic.js';

// The thin slice's scene (design.md §10): an exosome in plasma. Its biology comes from a cellPACKgpu recipe (Ludo's
// `exo_serialized.json`, trimmed to 14 ingredients), its membrane from a cryo-ET segmentation, a few of its catalase
// copies from template matching in the same tomogram. The cryo-ET data are synthetic fixtures, labelled as such;
// the recipe is real. One document ties them: the recipe and the picks are inputs of models, the segmentation is the
// compartment's geometry, and the activities say which data came from which.

export const ExosomeRecipe = recipeJson as unknown;

export const ExosomeResources: Readonly<Record<string, () => unknown>> = {
  'r.recipe': () => ExosomeRecipe,
  'r.membrane-mesh': () => syntheticVesicleObj(),
  'r.picks': () => syntheticPicksStar(),
};

const Fixture = { meso: { fixture: 'synthetic: generated by examples/fixtures/synthetic.ts; not a measurement' } };

export function exosomeDoc(): MesoViewSpecDoc {
  const imported = importCellpackGpuRecipe(parseCellpackGpuRecipe(ExosomeRecipe), { resource: 'r.recipe', modelId: 'm.recipe', seed: 1 });
  // the exosome's boundary is the segmented membrane, not the recipe's 50 nm sphere
  const compartments = imported.compartments.map((c) =>
    c.id === 'c.exosome'
      ? { ...c, label: 'exosome', geometry: { kind: 'mesh' as const, resource: 'r.membrane-mesh' }, evidence: ['ev.membrane-segmented'] }
      : c,
  );
  const observed: Population = {
    id: 'p.catalase.observed',
    entity: 'e.catalase',
    compartment: 'c.exosome',
    location: 'interior',
    abundance: { count: 24 },
    evidence: ['ev.catalase-picked'],
  };
  const lipids: Population = {
    id: 'p.lipids',
    entity: 'e.lipid',
    compartment: 'c.exosome',
    location: 'membrane',
    abundance: { density: { value: 1 / 0.65, unit: 'per_nm2' } },
    arrangement: { kind: 'bilayer' },
    evidence: ['ev.lipid-area'],
  };
  return {
    format: 'meso_view_spec',
    version: '0.1.0',
    metadata: {
      title: 'Exosome in plasma',
      description:
        'A cellPACKgpu exosome recipe (trimmed) packed inside a membrane segmented from a cryo-electron tomogram, with catalase copies picked in the same tomogram. The tomogram, segmentation and picks are synthetic fixtures.',
      authors: ['Ludo Autin'],
      created: '2026-11-08',
      organism: { name: 'Homo sapiens', taxon: 9606 },
      keywords: ['exosome', 'extracellular vesicle', 'cellPACK', 'cryo-ET'],
    },
    units: { length: 'nm' },
    frames: [
      { id: 'f.model', kind: 'world', units: 'nm', handedness: 'right', convention: 'origin at the vesicle centroid' },
      { id: 'f.tomo', kind: 'instrument', units: 'nm', voxelSize: 1, handedness: 'right', convention: "voxel indices, origin at the first voxel's corner" },
    ],
    alignments: [
      {
        id: 'al.tomo-model',
        from: 'f.tomo',
        to: 'f.model',
        transform: { translation: [-200, -200, -100] },
        method: 'centred on the segmentation centroid',
        activity: 'act.align',
      },
    ],
    resources: [
      { id: 'r.recipe', kind: 'recipe', format: 'cellpack-gpu-serialized', label: 'cellPACKgpu exosome recipe (exo_serialized.json, trimmed)', uri: 'examples/fixtures/exosome.cellpack-gpu.json' },
      { id: 'r.tilts', kind: 'tilt-series', format: 'mrc', label: 'tilt series', uri: 'fixture://tilts.mrc', custom: Fixture },
      { id: 'r.tomogram', kind: 'tomogram', format: 'mrc', label: 'tomogram', frame: 'f.tomo', uri: 'fixture://tomo_01.mrc', custom: Fixture },
      { id: 'r.membrane-mesh', kind: 'segmentation', format: 'obj', label: 'vesicle membrane, segmented', frame: 'f.tomo', uri: 'fixture://membrane.obj', custom: Fixture },
      { id: 'r.picks', kind: 'placements', format: 'relion-star', label: 'catalase picks', frame: 'f.tomo', uri: 'fixture://catalase_picks.star', custom: Fixture },
      { id: 'r.8cat', kind: 'structure', format: 'pdb-id', accession: { db: 'PDB', id: '8CAT' }, label: 'catalase' },
    ],
    entities: [
      ...imported.entities.map((e) => (e.id === 'e.catalase' ? { ...e, structure: { resource: 'r.8cat', assembly: '1' } } : e)),
      { id: 'e.lipid', label: 'phospholipid', kind: 'lipid', radius: { value: 4.5, unit: 'A' } },
    ],
    compartments,
    populations: [...imported.populations, observed, lipids],
    relations: [{ id: 'rel.tetraspanins', kind: 'colocalizes', subjects: ['p.CD9', 'p.CD63'], note: 'tetraspanin-enriched microdomains', evidence: ['ev.tetraspanin-web'] }],
    models: [
      { id: 'm.picks', label: 'catalase, picked', kind: 'precomputed', method: 'meso.precomputed', populations: ['p.catalase.observed'], inputs: ['r.picks'], activity: 'act.pick' },
      { ...imported.models[0], avoid: ['m.picks'], activity: 'act.pack' },
    ],
    evidence: [
      ...imported.evidence,
      { id: 'ev.membrane-segmented', kind: 'observation', statement: 'The vesicle membrane, segmented in the tomogram', source: { resource: 'r.membrane-mesh' }, confidence: 'high' },
      { id: 'ev.catalase-picked', kind: 'observation', statement: '24 catalase copies found by template matching (synthetic picks)', source: { resource: 'r.picks' }, confidence: 'medium' },
      { id: 'ev.lipid-area', kind: 'assumption', statement: '0.65 nm² per lipid per leaflet, a typical phospholipid area', confidence: 'medium' },
      { id: 'ev.tetraspanin-web', kind: 'assumption', statement: 'CD9 and CD63 co-cluster in tetraspanin-enriched microdomains (stated for the example; no citation attached)', confidence: 'low' },
    ],
    activities: [
      { id: 'act.acquire', kind: 'acquisition', label: 'tilt series acquired', generated: ['r.tilts'], software: { name: 'synthetic fixture' } },
      { id: 'act.reconstruct', kind: 'reconstruction', label: 'tomogram reconstructed', used: ['r.tilts'], generated: ['r.tomogram'], software: { name: 'synthetic fixture' } },
      { id: 'act.segment', kind: 'segmentation', label: 'membrane segmented', used: ['r.tomogram'], generated: ['r.membrane-mesh'], software: { name: 'synthetic fixture' } },
      { id: 'act.pick', kind: 'particle-picking', label: 'catalase template matching', used: ['r.tomogram', 'r.8cat'], generated: ['r.picks'], software: { name: 'synthetic fixture' } },
      { id: 'act.align', kind: 'alignment', label: 'tomogram to model frame', used: ['r.membrane-mesh'], generated: ['al.tomo-model'] },
      { id: 'act.pack', kind: 'modeling', label: 'recipe packed in the segmented membrane', used: ['r.recipe', 'r.membrane-mesh', 'r.picks'], generated: ['m.recipe'], software: { name: 'MesoViewSpec prototype', version: '0.1.0' } },
    ],
    views: [
      {
        id: 'v.overview',
        label: 'Overview',
        camera: { position: [0, 0, 260], target: [0, 0, 0], up: [0, 1, 0] },
        looks: [
          { select: { populations: ['p.lipids'] }, color: '#e8d8b0', transparency: 0.6 },
          { select: { entities: ['e.catalase'] }, color: '#d0453a' },
          { select: { populations: ['p.catalase.observed'] }, color: '#ffb000' },
        ],
        annotations: [{ id: 'an.picks', target: { populations: ['p.catalase.observed'] }, text: 'Catalase found by template matching (synthetic)', evidence: ['ev.catalase-picked'] }],
      },
      {
        id: 'v.lumen',
        label: 'Lumen only',
        camera: { position: [0, 0, 160], target: [0, 0, 0], up: [0, 1, 0] },
        looks: [
          { select: { compartments: ['medium'] }, visible: false },
          { select: { populations: ['p.lipids'] }, visible: false },
          { select: { entities: ['e.catalase'] }, color: '#d0453a' },
        ],
        selection: { populations: ['p.catalase.observed'] },
      },
    ],
    session: { view: 'v.overview' },
  };
}
