import type { Activity, Evidence, Id, MesoViewSpecDoc, Resource } from './doc.js';

// Tracing (_spec/format.md): from a modeled feature (a population, a compartment, a model, a resource) back to the
// evidence and the processing that produced it. The document's provenance is a graph: resources are used and generated
// by activities (W3C PROV's entities and activities), models and alignments come from activities, and any node cites
// evidence. A trace walks it backwards, each step saying why it was taken.

export interface TraceStep {
  readonly depth: number;
  readonly id: Id;
  readonly kind: 'population' | 'entity' | 'compartment' | 'model' | 'resource' | 'activity' | 'evidence' | 'alignment';
  /** Why this step follows its parent: `realized by`, `geometry from`, `generated by`, `used`, `cites`, … */
  readonly via: string;
  readonly label: string;
}

export function trace(doc: MesoViewSpecDoc, start: Id): TraceStep[] {
  const byId = <T extends { id: Id }>(xs: readonly T[] | undefined) => new Map((xs ?? []).map((x) => [x.id, x]));
  const pops = byId(doc.populations);
  const ents = byId(doc.entities);
  const comps = byId(doc.compartments);
  const models = byId(doc.models);
  const res = byId(doc.resources);
  const acts = byId(doc.activities);
  const evs = byId(doc.evidence);
  const als = byId(doc.alignments);
  const generatedBy = new Map<Id, Activity>();
  for (const a of doc.activities ?? []) for (const g of a.generated ?? []) generatedBy.set(g, a);
  const modelOf = new Map<Id, Id>();
  for (const m of doc.models ?? []) for (const p of m.populations) modelOf.set(p, m.id);

  const out: TraceStep[] = [];
  const seen = new Set<Id>();
  const step = (id: Id | undefined, via: string, depth: number) => {
    if (!id) return;
    const first = !seen.has(id);
    seen.add(id);
    const push = (kind: TraceStep['kind'], label: string) => out.push({ depth, id, kind, via, label });
    const cites = (ids: readonly Id[] | undefined) => (ids ?? []).forEach((e) => step(e, 'cites', depth + 1));
    const p = pops.get(id);
    if (p) {
      push('population', `${ents.get(p.entity)?.label ?? p.entity} in ${p.compartment} (${p.location})`);
      if (!first) return;
      cites(p.evidence);
      step(p.entity, 'is copies of', depth + 1);
      step(p.compartment, 'is in', depth + 1);
      step(modelOf.get(id), 'realized by', depth + 1);
      return;
    }
    const e = ents.get(id);
    if (e) {
      push('entity', e.label);
      if (!first) return;
      cites(e.evidence);
      step(e.structure?.resource, 'structure from', depth + 1);
      return;
    }
    const c = comps.get(id);
    if (c) {
      push('compartment', c.label);
      if (!first) return;
      cites(c.evidence);
      const g = c.geometry;
      if (g.kind === 'mesh' || g.kind === 'segmentation') step(g.resource, 'geometry from', depth + 1);
      return;
    }
    const m = models.get(id);
    if (m) {
      push('model', `${m.label ?? m.id} (${m.kind}, ${m.method})`);
      if (!first) return;
      cites(m.evidence);
      step(m.activity, 'made by', depth + 1);
      (m.inputs ?? []).forEach((r) => step(r, 'input', depth + 1));
      (m.avoid ?? []).forEach((r) => step(r, 'avoids', depth + 1));
      return;
    }
    const r: Resource | undefined = res.get(id);
    if (r) {
      const acc = r.accession ? ` ${r.accession.db}:${r.accession.id}` : '';
      push('resource', `${r.label ?? r.id} [${r.kind}, ${r.format}]${acc}`);
      if (!first) return;
      const a = generatedBy.get(id);
      if (a) step(a.id, 'generated by', depth + 1);
      if (r.frame) for (const al of doc.alignments ?? []) if (al.from === r.frame) step(al.id, 'aligned by', depth + 1);
      return;
    }
    const a = acts.get(id);
    if (a) {
      const sw = a.software ? ` with ${a.software.name}${a.software.version ? ` ${a.software.version}` : ''}` : '';
      push('activity', `${a.label ?? a.kind}${sw}`);
      if (!first) return;
      (a.used ?? []).forEach((u) => step(u, 'used', depth + 1));
      return;
    }
    const al = als.get(id);
    if (al) {
      push('alignment', `${al.from} → ${al.to}${al.method ? ` (${al.method})` : ''}`);
      if (!first) return;
      cites(al.evidence);
      step(al.activity, 'made by', depth + 1);
      return;
    }
    const ev: Evidence | undefined = evs.get(id);
    if (ev) {
      push('evidence', `${ev.kind}: ${ev.statement}`);
      if (!first) return;
      step(ev.source?.resource, 'source', depth + 1);
    }
  };
  step(start, 'start', 0);
  return out;
}

/** A trace as indented lines, for a UI or a test. */
export function traceToText(steps: readonly TraceStep[]): string {
  return steps
    .map((s) => `${'  '.repeat(s.depth)}${s.depth ? `${s.via} ` : ''}${s.kind} ${s.id}: ${s.label}`)
    .join('\n');
}

/**
 * A trace as a tree for the S-expression spelling (_spec/format.md): each step a form headed by its kind, its id first,
 * the steps it leads to grouped under the keyword of their relation (`:cites`, `:realized-by`, `:generated-by`, …).
 */
export function traceToSexprData(steps: readonly TraceStep[]): unknown {
  type N = { kind: string; ref: string; label: string } & Record<string, unknown>;
  const camel = (via: string) => via.replace(/ ([a-z])/g, (_, c: string) => c.toUpperCase());
  const roots: N[] = [];
  const stack: N[] = [];
  for (const s of steps) {
    const node: N = { kind: s.kind, ref: s.id, label: s.label };
    stack.length = s.depth;
    const parent = stack[s.depth - 1];
    if (parent) ((parent[camel(s.via)] ??= []) as N[]).push(node);
    else roots.push(node);
    stack[s.depth] = node;
  }
  return roots.length === 1 ? roots[0] : roots;
}
