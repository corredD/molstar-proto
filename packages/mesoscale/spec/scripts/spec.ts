// The MesoViewSpec spec check (packages/mesoscale/_spec/README.md), modelled on Seq*'s packages/sequences/scripts/spec.ts:
//   - the references in `_spec/reference/` are the code's tables, regenerated: the document's types (`format/doc.ts`),
//     the issue codes (`format/issues.ts`), MesoQL's symbols (`format/mesoql.ts`) and the built-in resolvers
//     (`resolvers/index.ts`); a file that differs from what the code gives, or is missing, is a miss;
//   - every `.ts` and `.tsx` source file under packages/mesoscale starts with Mol*'s header (a copyright line and an
//     `@author`);
//   - every link between `_spec` files resolves: the file exists and, for a Markdown file, so does the heading its
//     `#anchor` names, the slug being GitHub's anchor of the heading;
//   - every issue code the sources pass to `issue(…)` is in the registry of `format/issues.ts`.
// Exit 1 on a miss, printing each with where it is.
//
// Usage (from packages/mesoscale/spec; `pnpm spec` runs `check`):
//   pnpm spec [check|generate]   (check by default)
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import ts from '@typescript/typescript6';

export const SPEC_PACKAGE = join(import.meta.dirname, '..');
export const MESOSCALE = join(SPEC_PACKAGE, '..');
export const SPEC_DIR = join(MESOSCALE, '_spec');
const GENERATED_BY = 'packages/mesoscale/spec/scripts/spec.ts';

// ---- Markdown helpers ------------------------------------------------------------------------------------------

const FENCE = /^\s*(```|~~~)/;

/** GitHub's anchor of a heading: lowercased, markup and punctuation dropped, spaces to hyphens. */
export function slugOf(heading: string): string {
  return heading
    .replace(/\\(.)/g, '$1')
    .replace(/`/g, '')
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s/g, '-');
}

/** A Markdown file's anchors, a repeated heading's as GitHub numbers them (`-1`, `-2`); fenced code is skipped. */
export function anchorsOf(text: string): Set<string> {
  const set = new Set<string>();
  let fence = false;
  for (const line of text.split('\n')) {
    if (FENCE.test(line)) fence = !fence;
    const m = !fence && /^#{1,6}\s+(.*?)(?:\s+#+)?\s*$/.exec(line);
    if (!m) continue;
    const base = slugOf(m[1]);
    let slug = base;
    for (let n = 1; set.has(slug); n++) slug = `${base}-${n}`;
    set.add(slug);
  }
  return set;
}

function walk(dir: string, keep: (f: string) => boolean, out: string[] = []): string[] {
  for (const name of readdirSync(dir).sort()) {
    if (name === 'node_modules' || name === 'dist' || name === 'lib') continue;
    const f = join(dir, name);
    if (statSync(f).isDirectory()) walk(f, keep, out);
    else if (keep(f)) out.push(f);
  }
  return out;
}

function cell(text: string): string {
  return text.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
}

function table(head: string[], rows: string[][]): string {
  return [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`),
  ].join('\n');
}

function banner(from: string): string {
  return `<!-- Generated by ${GENERATED_BY} from ${from}. Do not edit: change the code, then run \`pnpm -C packages/mesoscale/spec spec generate\`. -->`;
}

// ---- The document's types (format/doc.ts), read with the TypeScript compiler API --------------------------------

/** The text of the JSDoc comment before a node, its markers dropped and its lines joined. */
function docOf(node: ts.Node, text: string): string {
  const ranges = ts.getLeadingCommentRanges(text, node.getFullStart()) ?? [];
  const last = ranges.filter((r) => text.startsWith('/**', r.pos)).pop();
  if (!last) return '';
  return text
    .slice(last.pos + 3, last.end - 2)
    .split('\n')
    .map((l) => l.replace(/^\s*\*?\s?/, ''))
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function code(text: string): string {
  return `\`${text.replace(/\s+/g, ' ').trim()}\``;
}

/** The exported interfaces and type aliases of a source file, as Markdown: a field table per interface. */
export function typesReference(source: string, text: string): string {
  const file = ts.createSourceFile(source, text, ts.ScriptTarget.Latest, true);
  const out: string[] = [];
  for (const node of file.statements) {
    if (!ts.isInterfaceDeclaration(node) && !ts.isTypeAliasDeclaration(node)) continue;
    if (!node.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)) continue;
    const tparams = node.typeParameters ? `<${node.typeParameters.map((p) => p.getText(file)).join(', ')}>` : '';
    out.push(`## ${node.name.text}${tparams ? ` ${code(tparams)}` : ''}`);
    const doc = docOf(node, text);
    if (doc) out.push(cell(doc));
    if (ts.isInterfaceDeclaration(node)) {
      const rows: string[][] = [];
      for (const m of node.members) {
        if (!ts.isPropertySignature(m) && !ts.isMethodSignature(m)) continue;
        const name = m.name.getText(file);
        rows.push([
          `\`${name}${m.questionToken ? '?' : ''}\``,
          m.type ? code(m.type.getText(file)) : '',
          docOf(m, text),
        ]);
      }
      if (rows.length) out.push(table(['Field', 'Type', 'Meaning'], rows));
    } else if (ts.isUnionTypeNode(node.type)) {
      out.push(node.type.types.map((t) => `- ${code(t.getText(file))}`).join('\n'));
    } else {
      out.push(code(node.type.getText(file)));
    }
  }
  return out.join('\n\n');
}

// ---- The generated references ----------------------------------------------------------------------------------

export type Loaded = {
  doc: string;
  issuesSource: string;
  issueCodes: Readonly<Record<string, string>>;
  symbols: readonly {
    name: string;
    full: string;
    returns: string;
    description: string;
    args: readonly { name: string; kind: string; ref?: string; rest?: boolean; optional?: boolean }[];
    keywords?: Readonly<Record<string, string>>;
    example: string;
  }[];
  resolvers: readonly {
    id: string;
    version: string;
    description: string;
    arrangements: readonly string[];
    locations: readonly string[];
    honours?: readonly string[];
    formats?: readonly string[];
  }[];
};

export async function load(): Promise<Loaded> {
  const src = join(SPEC_PACKAGE, 'src');
  const [issues, mesoql, resolvers] = await Promise.all([
    import(join(src, 'format/issues.ts')),
    import(join(src, 'format/mesoql.ts')),
    import(join(src, 'resolvers/index.ts')),
  ]);
  return {
    doc: readFileSync(join(src, 'format/doc.ts'), 'utf8'),
    issuesSource: readFileSync(join(src, 'format/issues.ts'), 'utf8'),
    issueCodes: issues.IssueCodes,
    symbols: mesoql.MesoQLSymbols,
    resolvers: resolvers.DefaultResolvers,
  };
}

function list(items: readonly string[] | undefined): string {
  return items?.length ? items.map((i) => `\`${i}\``).join(', ') : '';
}

/** The generated files, by name in `_spec/reference/`, as the code gives them (before the formatter). */
export function referenceFiles(l: Loaded): Record<string, string> {
  const head = (title: string, from: string, intro: string) =>
    `${banner(from)}\n\n# MesoViewSpec: reference, ${title}\n\n${intro}`;
  const files: Record<string, string> = {};

  files['format.md'] = [
    head(
      'the document',
      '`format/doc.ts`',
      'Every type the document is made of, with its fields. What a node means is in [format.md](../format.md); an optional field is marked `?`.',
    ),
    typesReference('doc.ts', l.doc),
  ].join('\n\n');

  files['issues.md'] = [
    head(
      'issues',
      '`format/issues.ts`',
      'What the runtime reports, as data a UI can explain. A code has one severity; the message says why.',
    ),
    typesReference('issues.ts', l.issuesSource),
    '## Codes',
    table(
      ['Code', 'Meaning'],
      Object.entries(l.issueCodes).map(([c, m]) => [`\`${c}\``, m]),
    ),
  ].join('\n\n');

  files['mesoql.md'] = [
    head(
      'MesoQL symbols',
      '`format/mesoql.ts` (`MesoQLSymbols`)',
      'The symbols a MesoQL address is made of. What an address means is in [mesoql.md](../mesoql.md). A `…` marks arguments that take the rest, `?` an optional one, `:name` a keyword.',
    ),
    table(
      ['Symbol', 'Full name', 'Returns', 'Arguments', 'Keywords', 'Meaning', 'Example'],
      l.symbols.map((s) => [
        `\`${s.name}\``,
        `\`${s.full}\``,
        s.returns,
        s.args.map((a) => `\`${a.name}${a.rest ? '…' : ''}${a.optional ? '?' : ''}\` (${a.ref ?? a.kind})`).join(', '),
        Object.entries(s.keywords ?? {})
          .map(([k, t]) => `\`:${k}\` (${t})`)
          .join(', '),
        s.description,
        `\`${s.example}\``,
      ]),
    ),
  ].join('\n\n');

  files['resolvers.md'] = [
    head(
      'built-in resolvers',
      '`resolvers/index.ts` (`DefaultResolvers`)',
      'The resolvers the runtime has by default; a host adds its own to the list. What a resolver is for, and the contract, is in [runtime.md](../runtime.md). The version is bumped when the same input gives a different result.',
    ),
    table(
      ['Id', 'Version', 'Arrangements', 'Locations', 'Formats', 'Honours', 'Meaning'],
      l.resolvers.map((r) => [
        `\`${r.id}\``,
        r.version,
        list(r.arrangements),
        list(r.locations),
        list(r.formats),
        list(r.honours),
        r.description,
      ]),
    ),
  ].join('\n\n');

  return files;
}

/** The formatter the repository's Markdown goes through (Prettier, with the repository's config). */
export async function formatMarkdown(files: Record<string, string>): Promise<Record<string, string>> {
  const prettier = await import('prettier');
  const out: Record<string, string> = {};
  for (const [name, text] of Object.entries(files)) {
    const path = join(SPEC_DIR, 'reference', name);
    const config = (await prettier.resolveConfig(path)) ?? {};
    out[name] = await prettier.format(text, { ...config, filepath: path });
  }
  return out;
}

/** What `_spec/reference/` holds, regenerated from the code and formatted. */
export async function generateReference(): Promise<Record<string, string>> {
  return formatMarkdown(referenceFiles(await load()));
}

// ---- The checks --------------------------------------------------------------------------------------------------

export interface CheckOptions {
  /** The spec folder, its `reference/` inside. */
  readonly spec: string;
  /** Where the sources are (every `.ts` and `.tsx` under it needs the header). */
  readonly sources: string;
  /** What the references should hold, by file name. */
  readonly reference: Record<string, string>;
  /** The issue codes registered, for the check of what the sources pass to `issue(…)`. */
  readonly issueCodes?: Readonly<Record<string, string>>;
  /** Where the sources that report with those codes are (the adapters' own codes have their own namespaces). */
  readonly codeSources?: string;
  /** Paths in misses are shown from here. */
  readonly root: string;
}

/** The generated references against the files: stale or missing. */
export function checkReference(o: CheckOptions, misses: string[]) {
  const dir = join(o.spec, 'reference');
  for (const [name, want] of Object.entries(o.reference)) {
    const f = join(dir, name);
    if (!existsSync(f)) misses.push(`${relative(o.root, f)}\tmissing: run pnpm spec generate`);
    else if (readFileSync(f, 'utf8') !== want) misses.push(`${relative(o.root, f)}\tstale: run pnpm spec generate`);
  }
}

const HEADER_LINE =
  /^ \* Copyright \(c\) \d{4}(-\d{4})? mol\* contributors, licensed under MIT, See LICENSE file for more info\.$/;

/** Every `.ts` and `.tsx` source starts with Mol*'s header (after a shebang line, if any): the copyright line and an `@author`. */
export function checkHeaders(o: CheckOptions, misses: string[]): number {
  const files = walk(o.sources, (f) => /\.tsx?$/.test(f) && !f.endsWith('.d.ts'));
  for (const f of files) {
    // a CLI's shebang line comes before the header
    const all = readFileSync(f, 'utf8').split('\n', 9);
    const lines = all[0].startsWith('#!') ? all.slice(1) : all.slice(0, 8);
    const close = lines.indexOf(' */');
    if (lines[0] !== '/**' || !HEADER_LINE.test(lines[1] ?? ''))
      misses.push(`${relative(o.root, f)}:1\tno Mol* header`);
    else if (close < 0 || !lines.slice(2, close).some((l) => /^ \* @author \S/.test(l)))
      misses.push(`${relative(o.root, f)}:1\tthe header has no @author`);
  }
  return files.length;
}

const LINK = /(?<!!)\[[^\]]*\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g;
const LINK_DEFINITION = /^ {0,3}\[[^\]]+\]:\s*(\S+)/gm;
const HTML_LINK = /<a\s[^>]*href="([^"]+)"/g;

/** The text with fenced code and inline code blanked, its line breaks kept (so an index still gives its line). */
function withoutCode(text: string): string {
  let fence = false;
  return text
    .split('\n')
    .map((l) => {
      const f = FENCE.test(l);
      if (f) fence = !fence;
      return f || fence ? '' : l;
    })
    .join('\n')
    .replace(/`[^`]*`/g, (c) => c.replace(/[^\n]/g, ' '));
}

/** Every link between `_spec` files resolves: the file, and the heading an anchor names. Inline links (their text
 * may wrap over lines, a title may follow), reference definitions and `<a href>` are read. */
export function checkLinks(o: CheckOptions, misses: string[]): number {
  const cache = new Map<string, Set<string>>();
  const heads = (f: string) => {
    let set = cache.get(f);
    if (!set) cache.set(f, (set = anchorsOf(readFileSync(f, 'utf8'))));
    return set;
  };
  let count = 0;
  for (const file of walk(o.spec, (f) => f.endsWith('.md'))) {
    const text = withoutCode(readFileSync(file, 'utf8'));
    for (const re of [LINK, LINK_DEFINITION, HTML_LINK]) {
      for (const m of text.matchAll(re)) {
        const target = m[1];
        if (/^[a-z][a-z0-9+.-]*:/i.test(target)) continue;
        count++;
        const [path, anchor] = target.split('#');
        const to = path ? resolve(dirname(file), path) : file;
        const where = `${relative(o.root, file)}:${text.slice(0, m.index).split('\n').length}\t${target}`;
        if (!existsSync(to)) misses.push(`${where}: no such file`);
        else if (anchor && to.endsWith('.md') && !heads(to).has(anchor)) misses.push(`${where}: no such heading`);
      }
    }
  }
  return count;
}

const ISSUE_CALL = /\bissue\(\s*['"`]([^'"`$]+)['"`]/g;
// MesoQL's parser reports through `err('code', …)`, which prefixes the namespace; validate.ts's helpers `err` and
// `warn` take the whole code.
const MESOQL_ERR_CALL = /\berr\(\s*'([a-z.-]+)'/g;
const HELPER_CALL = /\b(?:err|warn)\(\s*['"]([a-z]+(?:\.[a-z-]+)+)['"]/g;

/** Every issue code a source passes to `issue(…)` or to validate.ts's `err` and `warn` is registered. */
export function checkIssueCodes(o: CheckOptions, misses: string[]) {
  if (!o.issueCodes) return;
  for (const f of walk(o.codeSources ?? o.sources, (f) => /\.tsx?$/.test(f) && !f.includes('/_test/'))) {
    const text = readFileSync(f, 'utf8');
    const mesoql = f.endsWith('format/mesoql.ts');
    const named = [...text.matchAll(ISSUE_CALL), ...(mesoql ? [] : [...text.matchAll(HELPER_CALL)])].map((m) => ({
      code: m[1],
      at: m.index,
    }));
    if (mesoql) for (const m of text.matchAll(MESOQL_ERR_CALL)) named.push({ code: `mesoql.${m[1]}`, at: m.index });
    for (const { code, at } of named) {
      if (code in o.issueCodes) continue;
      const line = text.slice(0, at).split('\n').length;
      misses.push(`${relative(o.root, f)}:${line}\t"${code}" is in no registry of format/issues.ts`);
    }
  }
}

export function check(o: CheckOptions): string[] {
  const misses: string[] = [];
  checkReference(o, misses);
  checkHeaders(o, misses);
  checkLinks(o, misses);
  checkIssueCodes(o, misses);
  return misses;
}

// ---- Command line ------------------------------------------------------------------------------------------------

async function main(command: string | undefined) {
  const root = resolve(MESOSCALE, '..', '..');
  if (command === 'generate') {
    const dir = join(SPEC_DIR, 'reference');
    mkdirSync(dir, { recursive: true });
    const files = await generateReference();
    for (const [name, text] of Object.entries(files)) writeFileSync(join(dir, name), text);
    console.log(`wrote ${Object.keys(files).length} references to ${relative(root, dir)}`);
  } else if (command === 'check') {
    const l = await load();
    const reference = await formatMarkdown(referenceFiles(l));
    const misses = check({
      spec: SPEC_DIR,
      sources: MESOSCALE,
      codeSources: join(SPEC_PACKAGE, 'src'),
      reference,
      issueCodes: l.issueCodes,
      root,
    });
    if (misses.length) {
      console.error(`spec: ${misses.length} miss${misses.length === 1 ? '' : 'es'}\n${misses.join('\n')}`);
      process.exit(1);
    }
    console.log('spec: ok');
  } else {
    console.error('usage: spec.ts <check|generate>');
    process.exit(2);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) await main(process.argv[2] ?? 'check');
