"""Trains the network (plan C2) on the training maps' pairs, validates on their held-back configurations, never reads
the held-out maps; writes the weights JSON (`--out`)."""

import argparse
import glob
import json
import os

import numpy as np
import torch

from vl.config import DATA_DIR
from vl.data import HELD_OUT, VAL_EVERY
from vl.net import Net, relative_loss, volumetric


def load(files):
    parts = [dict(np.load(f)) for f in files]
    d = {k: np.concatenate([p[k] for p in parts]) for k in parts[0]}
    x = torch.from_numpy(np.concatenate([d['desc'], d['albedo'][:, None]], 1))
    y = torch.from_numpy(np.stack([d['key'], d['amb']], 1))
    return x, y, d['config']


def report(name, pred, y):
    """per channel: mean ratio (Σ pred / Σ y) and the median relative error"""
    out = {}
    for i, ch in enumerate(('key', 'amb')):
        out[ch] = (float(pred[:, i].sum() / y[:, i].sum()), float(((pred[:, i] - y[:, i]).abs() / y[:, i].clamp(min=1e-2)).median()))
    print(f'  {name:10s} ' + '  '.join(f'{ch} ratio {r:.3f} med.rel.err {e:.3f}' for ch, (r, e) in out.items()))
    return out


HEADER = """/**
 * Copyright (c) 2026 mol* contributors, licensed under MIT, See LICENSE file for more info.
 *
 * @author Ludovic Autin <autin@scripps.edu>
 */

// Generated by tools/volume-lighting/train.py, do not edit: the weights of the neural volume lighting's network
// (volume-lighting.md §C), a JSON literal (the package compiles without JSON modules). `check`: inputs and the
// outputs PyTorch gives them, for the TypeScript and WGSL networks' tests.
"""


def write_weights(net: Net, path: str, validation: dict, xv: torch.Tensor):
    """the module, its check: 8 validation inputs (the training distribution, not saturated) and PyTorch's outputs"""
    j = net.export()
    gen = torch.Generator().manual_seed(1)
    x = xv[torch.randperm(len(xv), generator=gen)[:8]]
    with torch.no_grad():
        j['check'] = {'inputs': x.reshape(-1).tolist(), 'outputs': net(x).reshape(-1).tolist()}
    j['validation'] = validation
    with open(path, 'w') as f:
        f.write(HEADER + 'export const VolumeNeuralWeights = ' + json.dumps(j, separators=(',', ':')) + ';\n')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--epochs', type=int, default=40)
    ap.add_argument('--lr', type=float, default=3e-3)
    ap.add_argument('--batch', type=int, default=2048)
    ap.add_argument('--seed', type=int, default=0)
    ap.add_argument('--out', default=None)
    a = ap.parse_args()
    torch.manual_seed(a.seed)
    files = sorted(f for f in glob.glob(os.path.join(DATA_DIR, 'pairs', '*.npz'))
                   if not any(os.path.basename(f).split('.')[0] == h.split('.')[0] for h in HELD_OUT))
    x, y, config = load(files)
    val = torch.from_numpy(config % VAL_EVERY == VAL_EVERY - 1)
    xt, yt, xv, yv = x[~val], y[~val], x[val], y[val]
    print(f'{len(files)} training maps: {len(xt)} pairs, {len(xv)} validation')
    net = Net()
    net.fit_normalization(xt)
    opt = torch.optim.Adam(net.parameters(), lr=a.lr)
    steps = a.epochs * (len(xt) // a.batch)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, a.lr, total_steps=steps)
    for epoch in range(a.epochs):
        perm = torch.randperm(len(xt))
        for s in range(len(xt) // a.batch):
            i = perm[s * a.batch : (s + 1) * a.batch]
            loss = relative_loss(net(xt[i]), yt[i])
            opt.zero_grad()
            loss.backward()
            opt.step()
            sched.step()
        if epoch % 10 == 9 or epoch == a.epochs - 1:
            with torch.no_grad():
                print(f'epoch {epoch + 1}: train {float(loss):.4f} val {float(relative_loss(net(xv), yv)):.4f}')
    with torch.no_grad():
        print('validation:')
        res = {'neural': report('neural', net(xv), yv), 'volumetric': report('volumetric', torch.stack(volumetric(xv[:, :13]), 1), yv)}
    if a.out:
        write_weights(net, a.out, res, xv)
        print('wrote', a.out)
